import ast
import base64
import csv
import io
import re
from pathlib import Path

from packaging.version import InvalidVersion, Version

from ..services.http import NotFound
from .base import AnalysisInputError, EcosystemAdapter, ReleaseInfo

NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,200}$")
SETUPTOOLS_COMMANDS = {"install", "develop", "egg_info", "build_py", "build_ext", "sdist", "bdist_wheel", "bdist_egg", "build", "install_lib", "install_scripts"}
URL_PRIORITY = ["source", "source code", "repository", "code", "github", "homepage", "home"]


class PyPIAdapter(EcosystemAdapter):
    name = "pypi"
    label = "PyPI"
    base = "https://pypi.org/pypi"

    def _check(self, name):
        if not NAME_RE.match(name or ""):
            raise AnalysisInputError(f"invalid PyPI package name: {name!r}")

    def latest_version(self, name: str) -> str:
        self._check(name)
        try:
            return self.http.get_json(f"{self.base}/{name}/json", ttl=120)["info"]["version"]
        except NotFound as e:
            raise AnalysisInputError(f"PyPI package {name!r} not found") from e

    def resolve_release(self, name, version=None) -> ReleaseInfo:
        self._check(name)
        version = version or self.latest_version(name)
        try:
            data = self.http.get_json(f"{self.base}/{name}/{version}/json")
        except NotFound as e:
            raise AnalysisInputError(f"PyPI release {name}=={version} not found") from e
        info, urls = data["info"], data.get("urls", [])
        sdists = [u for u in urls if u["packagetype"] == "sdist"]
        wheels = [u for u in urls if u["packagetype"] == "bdist_wheel"]
        pure = [w for w in wheels if w["filename"].endswith("-none-any.whl")]
        pick = (sdists or pure or wheels or [None])[0]
        if not pick:
            raise AnalysisInputError(f"{name}=={version} has no downloadable distribution files")
        return ReleaseInfo(
            ecosystem="pypi", name=info["name"], version=info["version"], artifact_url=pick["url"],
            filename=pick["filename"], artifact_kind="sdist" if pick in sdists else "wheel",
            expected_hashes={"sha256": pick["digests"]["sha256"]}, repo_urls=self._repo_urls(info),
            published_at=pick.get("upload_time_iso_8601"),
            metadata={"summary": info.get("summary"), "author": info.get("author"), "license": info.get("license"),
                      "requires_python": info.get("requires_python"), "project_urls": info.get("project_urls") or {},
                      "available_files": [u["filename"] for u in urls]},
        )

    @staticmethod
    def _repo_urls(info) -> list[str]:
        pu = info.get("project_urls") or {}
        ranked = sorted(pu.items(), key=lambda kv: URL_PRIORITY.index(kv[0].lower()) if kv[0].lower() in URL_PRIORITY else 99)
        urls = [v for _, v in ranked] + [info.get("home_page"), info.get("download_url")]
        seen, out = set(), []
        for u in urls:
            if u and "github.com" in u and u not in seen:
                seen.add(u)
                out.append(u)
        return out

    def list_versions(self, name) -> list[dict]:
        self._check(name)
        try:
            data = self.http.get_json(f"{self.base}/{name}/json", ttl=120)
        except NotFound as e:
            raise AnalysisInputError(f"PyPI package {name!r} not found") from e
        out = []
        for v, files in data.get("releases", {}).items():
            if not files:
                continue
            try:
                pv = Version(v)
            except InvalidVersion:
                continue
            times = [f.get("upload_time_iso_8601") for f in files if f.get("upload_time_iso_8601")]
            out.append({"version": v, "published_at": min(times) if times else None, "prerelease": pv.is_prerelease,
                        "yanked": all(f.get("yanked") for f in files), "_v": pv})
        out.sort(key=lambda d: d["_v"])
        for d in out:
            d.pop("_v")
        return out

    def classify_expected(self, rel_path):
        parts = rel_path.split("/")
        if rel_path == "PKG-INFO":
            return "Core metadata (PKG-INFO) generated by the build backend"
        if any(p.endswith(".egg-info") for p in parts[:-1]):
            return "setuptools egg-info metadata generated at build time"
        if any(p.endswith(".dist-info") for p in parts[:-1]):
            return "Wheel .dist-info metadata generated at build time"
        return None

    def normalize_for_compare(self, rel_path, text):
        if rel_path.split("/")[-1] == "setup.cfg":
            return re.sub(r"\n*\[egg_info\][^\[]*", "\n", text).strip() + "\n"
        return text

    def install_hooks(self, root):
        hooks = []
        if root is None:
            return hooks
        setup = root / "setup.py"
        if setup.is_file():
            try:
                tree = ast.parse(setup.read_text("utf-8", "replace"))
            except (SyntaxError, ValueError):
                tree = None
            for node in ast.walk(tree) if tree else []:
                if isinstance(node, ast.ClassDef):
                    bases = {b.attr if isinstance(b, ast.Attribute) else getattr(b, "id", "") for b in node.bases}
                    overridden = bases & SETUPTOOLS_COMMANDS
                    if overridden:
                        hooks.append({"kind": "setup_cmdclass", "file": "setup.py", "line": node.lineno,
                                      "detail": f"class {node.name}({', '.join(sorted(overridden))}) overrides a setuptools command"})
                elif isinstance(node, ast.keyword) and node.arg == "cmdclass":
                    hooks.append({"kind": "setup_cmdclass_kw", "file": "setup.py", "line": getattr(node.value, "lineno", None),
                                  "detail": "setup() registers custom commands via cmdclass"})
        for pth in root.rglob("*.pth"):
            text = pth.read_text("utf-8", "replace")
            if any(line.lstrip().startswith("import") for line in text.splitlines()):
                hooks.append({"kind": "pth_import", "file": pth.relative_to(root).as_posix(), "line": 1,
                              "detail": ".pth file with import line runs at every interpreter start-up"})
        return hooks

    def build_manifest(self, root):
        for rec in root.glob("*.dist-info/RECORD"):
            entries = {}
            for row in csv.reader(io.StringIO(rec.read_text("utf-8", "replace"))):
                if row:
                    entries[row[0]] = row[1] if len(row) > 1 else ""
            return {"type": "RECORD", "file": rec.relative_to(root).as_posix(), "entries": entries}
        for src in root.glob("*.egg-info/SOURCES.txt"):
            entries = {line.strip(): "" for line in src.read_text("utf-8", "replace").splitlines() if line.strip()}
            return {"type": "SOURCES.txt", "file": src.relative_to(root).as_posix(), "entries": entries}
        return None

    def entry_points(self, root):
        eps = {"setup.py"} if (root / "setup.py").is_file() else set()
        return eps | {p.relative_to(root).as_posix() for p in root.rglob("__init__.py")}

    def source_prefix_hints(self):
        return ["src/", "lib/", "python/"]


def record_hash_matches(expected: str, data: bytes) -> bool:
    import hashlib

    if not expected or "=" not in expected:
        return True
    algo, b64 = expected.split("=", 1)
    try:
        digest = hashlib.new(algo, data).digest()
    except ValueError:
        return True
    return base64.urlsafe_b64encode(digest).rstrip(b"=").decode() == b64


def pkg_path(root: Path, rel: str) -> Path:
    return root / rel
