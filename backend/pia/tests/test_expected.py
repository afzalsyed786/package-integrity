"""Expected-difference recognition, source maps and false-positive avoidance."""
import json
from types import SimpleNamespace

from pia.adapters.npm import NpmAdapter
from pia.adapters.pypi import PyPIAdapter
from pia.adapters.synthetic import build_bundle
from pia.engine import sourcemap
from pia.engine.comparison import ComparisonEngine
from pia.engine.expected import ExpectedClassifier


def _tree(root, files):
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    return root


def _classify(tmp_path, profile, pkg_files, repo_files, version="1.0.0"):
    pkg, repo = _tree(tmp_path / "pkg", pkg_files), _tree(tmp_path / "repo", repo_files)
    comp = ComparisonEngine(profile, 2 * 1024 * 1024).compare(pkg, repo)
    ExpectedClassifier(profile, SimpleNamespace(version=version), 2 * 1024 * 1024).classify(comp)
    return {r.path: r for r in comp.records}


def test_pypi_metadata_version_stamp_and_setup_cfg(tmp_path):
    recs = _classify(tmp_path, PyPIAdapter(None, None), {
        "PKG-INFO": "Metadata-Version: 2.1\n", "x.egg-info/SOURCES.txt": "x/a.py\n",
        "setup.cfg": "[metadata]\nname = x\n\n[egg_info]\ntag_build = \ntag_date = 0\n",
        "x/_version.py": "# file generated by setuptools_scm\n__version__ = version = '1.0.0'\n",
        "x/a.py": "VERSION = '1.0.0'\n",
    }, {"setup.cfg": "[metadata]\nname = x\n", "x/a.py": "VERSION = '0.0.0.dev0'\n"})
    assert recs["PKG-INFO"].status == "expected"
    assert recs["x.egg-info/SOURCES.txt"].status == "expected"
    assert recs["setup.cfg"].status == "identical" and recs["setup.cfg"].normalized
    assert recs["x/_version.py"].status == "expected"
    assert recs["x/a.py"].status == "expected" and "Version stamp" in recs["x/a.py"].expected_reason


def test_generated_looking_file_with_code_is_not_expected(tmp_path):
    recs = _classify(tmp_path, PyPIAdapter(None, None), {
        "x/_version.py": "# file generated by setuptools_scm\nimport os\nos.system('id')\n__version__ = '1.0.0'\n"}, {"README.md": "x"})
    assert recs["x/_version.py"].status == "package_only"


def test_src_layout_alignment(tmp_path):
    recs = _classify(tmp_path, PyPIAdapter(None, None), {"x/__init__.py": "A = 1\n", "x/b.py": "B = 2\n"},
                     {"src/x/__init__.py": "A = 1\n", "src/x/b.py": "B = 2\n"})
    assert all(r.status == "identical" for r in recs.values())


def test_sourcemap_backed_bundle_expected_and_npm_package_json_normalised(tmp_path):
    src = "function f(a) {\n  return a + 1;\n}\nmodule.exports = f;\n"
    bundle, smap = build_bundle(src, "../src/index.js", "", "index.js.map")
    recs = _classify(tmp_path, NpmAdapter(None, None), {
        "dist/index.js": bundle, "dist/index.js.map": smap, "package.json": json.dumps({"name": "p", "gitHead": "abc", "_id": "p@1"}),
    }, {"src/index.js": src, "package.json": json.dumps({"name": "p"})})
    assert recs["dist/index.js"].status == "expected"
    assert recs["dist/index.js.map"].status == "expected"
    assert recs["package.json"].status == "identical"


def test_ts_compiled_output_expected(tmp_path):
    recs = _classify(tmp_path, NpmAdapter(None, None), {"lib/util.js": "exports.x = 1;\n", "lib/util.d.ts": "export declare const x: number;\n"},
                     {"src/util.ts": "export const x = 1;\n"})
    assert recs["lib/util.js"].status == "expected" and recs["lib/util.d.ts"].status == "expected"


def test_vlq_and_unmapped_lines():
    assert sourcemap.decode_vlq("AACA") == [0, 0, 1, 0]
    assert sourcemap.decode_vlq("gBAAA") == [16, 0, 0, 0]
    _, smap = build_bundle("a();\nb();\n", "../src/i.js", "evil();\n", "i.js.map")
    assert sourcemap.mapped_lines(json.loads(smap)["mappings"]) == [True, True, False]


def test_sourcemap_resolution():
    repo = {"src/index.js", "lib/x.js"}
    assert sourcemap.resolve_source("webpack://pkg/./src/index.js", "dist/a.js.map", "", repo) == "src/index.js"
    assert sourcemap.resolve_source("../src/index.js", "dist/a.js.map", "", repo) == "src/index.js"
    assert sourcemap.is_external_source("webpack://pkg/node_modules/lodash/x.js")
