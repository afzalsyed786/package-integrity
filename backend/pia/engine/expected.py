"""Expected-difference classifier driven by structure, build manifests and source maps (not path allow-lists)."""
import ast
import re
from pathlib import PurePosixPath

from . import sourcemap
from .filetypes import read_text

VERSION_LINE = re.compile(r"version|__version__|\d+\.\d+", re.I)
GENERATED_MARKER = re.compile(r"(file generated by|auto-?generated|do not edit|generated by)", re.I)


def _constant_module(text: str) -> bool:
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return False
    for node in tree.body:
        if isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant):
            continue
        if isinstance(node, (ast.Import, ast.ImportFrom)) and all(a.name.split(".")[0] in ("typing", "__future__", "TYPE_CHECKING", "Tuple", "Union") for a in node.names):
            continue
        if isinstance(node, ast.ImportFrom) and node.module in ("typing", "__future__"):
            continue
        if isinstance(node, ast.If) and isinstance(node.test, (ast.Name, ast.Constant)):
            continue
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            value = node.value
            if value is None or isinstance(value, ast.Constant) or (isinstance(value, ast.Tuple) and all(isinstance(e, ast.Constant) for e in value.elts)):
                continue
            if isinstance(value, ast.List) and all(isinstance(e, ast.Constant) for e in value.elts):
                continue
            if isinstance(value, ast.Name):
                continue
        return False
    return True


class ExpectedClassifier:
    def __init__(self, profile, release, max_text: int):
        self.profile = profile
        self.release = release
        self.max_text = max_text

    def classify(self, comparison) -> None:
        pkg_map, repo_map = comparison.pkg_map, comparison.repo_map
        repo_set = set(repo_map)
        self._maps = self._sourcemap_index(pkg_map, repo_set)
        for rec in comparison.records:
            if rec.status not in ("package_only", "modified"):
                continue
            reason = (self.profile.classify_expected(rec.path)
                      or self._version_stamp(rec, pkg_map, repo_map)
                      or self._compiled(rec, pkg_map, repo_set)
                      or self._sourcemap_backed(rec)
                      or self._transpiled(rec, repo_set)
                      or self._minified_variant(rec, pkg_map))
            if reason:
                rec.original_status, rec.status, rec.expected_reason = rec.status, "expected", reason

    def _version_stamp(self, rec, pkg_map, repo_map):
        ver = self.release.version
        text = read_text(pkg_map[rec.path], self.max_text)
        if text is None:
            return None
        if rec.status == "modified":
            old = read_text(repo_map[rec.repo_path], self.max_text)
            if old is None:
                return None
            a, b = old.splitlines(), text.splitlines()
            import difflib

            changed = [line for line in difflib.unified_diff(a, b, lineterm="", n=0)
                       if line[:1] in "+-" and not line.startswith(("+++", "---")) and line[1:].strip()]
            if changed and all(VERSION_LINE.search(line) for line in changed) and any(ver in line for line in changed if line.startswith("+")):
                return f"Version stamp: only version strings changed (set to {ver} at build time)"
            return None
        if rec.kind == "python" and rec.size < 4096 and ver in text and _constant_module(text):
            return "Generated version module: constant-only Python file carrying the release version"
        if rec.kind == "python" and rec.size < 4096 and GENERATED_MARKER.search(text[:400]) and _constant_module(text):
            return "Build-tool generated constant module"
        return None

    def _compiled(self, rec, pkg_map, repo_set):
        if rec.kind != "bytecode":
            return None
        p = PurePosixPath(rec.path)
        stem = p.name.split(".")[0]
        parent = p.parent.parent if p.parent.name == "__pycache__" else p.parent
        src = (parent / f"{stem}.py").as_posix().lstrip("./")
        if src in pkg_map or src in repo_set:
            return f"Compiled bytecode of {src} (verified separately by the bytecode detector)"
        return None

    def _sourcemap_index(self, pkg_map, repo_set):
        index = {}
        for rel, path in pkg_map.items():
            if not rel.endswith((".js", ".mjs", ".cjs")):
                continue
            text = read_text(path, self.max_text)
            if not text:
                continue
            map_rel, inline = sourcemap.find_map_reference(rel, text)
            smap = inline
            if map_rel and map_rel in pkg_map:
                mt = read_text(pkg_map[map_rel], self.max_text)
                smap = sourcemap.parse_map(mt) if mt else None
            if not smap:
                continue
            resolved = [sourcemap.resolve_source(s, map_rel or rel, smap.get("sourceRoot", ""), repo_set)
                        for s in smap["sources"] if isinstance(s, str) and not sourcemap.is_external_source(s)]
            hits = [r for r in resolved if r]
            index[rel] = {"map": map_rel, "sources": hits, "total": len(resolved)}
            if map_rel:
                index[map_rel] = index[rel]
        return index

    def _sourcemap_backed(self, rec):
        info = self._maps.get(rec.path)
        if info and info["sources"] and len(info["sources"]) >= max(1, info["total"] // 2):
            srcs = ", ".join(info["sources"][:3]) + ("…" if len(info["sources"]) > 3 else "")
            kind = "Source map" if rec.path.endswith(".map") else "Build output"
            return f"{kind} generated from repository sources ({srcs}); mapping verified by the source-map detector"
        return None

    def _transpiled(self, rec, repo_set):
        p = PurePosixPath(rec.path)
        name = p.name
        stem = re.sub(r"\.(d\.ts|d\.mts|d\.cts|js|mjs|cjs)$", "", name)
        if stem == name:
            return None
        for ext in (".ts", ".tsx", ".mts", ".cts", ".coffee", ".jsx"):
            for r in repo_set:
                if r.endswith("/" + stem + ext) or r == stem + ext:
                    return f"Compiled output of {r} (TypeScript/transpiler build artifact)"
        return None

    def _minified_variant(self, rec, pkg_map):
        if rec.path.endswith(".min.js"):
            base = rec.path[:-7] + ".js"
            if base in pkg_map and base in self._maps:
                return f"Minified variant of {base}"
        return None

    def sourcemap_index(self):
        return self._maps
